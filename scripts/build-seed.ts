/**
 * Generates `migrations/0002_seed.sql` from the verified content modules.
 *
 * - GitHub metrics come from `src/data/github-snapshot.json`, produced by
 *   scripts/fetch-github.ts against the live GitHub REST API.
 * - Editorial judgements come from src/content/*.ts.
 * The generated SQL is idempotent (INSERT ... ON CONFLICT DO UPDATE) and never
 * overwrites editorial columns with API data.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { CURATION } from "../src/content/curation.ts";
import { TUTORIALS, VERIFIED_AT } from "../src/content/tutorials.ts";
import { PATHS } from "../src/content/paths.ts";
import { GUIDES } from "../src/content/guides.ts";
import { CHIPS } from "../src/content/chips.ts";

interface SnapshotRepo {
  full_name: string;
  owner: string;
  html_url: string;
  description: string | null;
  topics: string[];
  language: string | null;
  license: string | null;
  stars: number;
  forks: number;
  open_issues: number;
  created_at: string;
  updated_at: string;
  pushed_at: string;
  archived: boolean;
  default_branch: string;
  homepage: string | null;
  latest_release: { tag: string; published_at: string; url: string } | null;
}

interface Snapshot {
  fetched_at: string;
  items: SnapshotRepo[];
}

const root = resolve(import.meta.dirname, "..");
const snapshot = JSON.parse(
  readFileSync(resolve(root, "src/data/github-snapshot.json"), "utf8"),
) as Snapshot;

function q(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  if (typeof value === "boolean") return value ? "1" : "0";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function j(value: unknown): string {
  return q(JSON.stringify(value));
}

export function slugFor(fullName: string): string {
  return fullName.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

const lines: string[] = [
  "-- AUTO-GENERATED by scripts/build-seed.ts — do not edit by hand.",
  `-- GitHub snapshot fetched at: ${snapshot.fetched_at}`,
  `-- Tutorials verified at: ${VERIFIED_AT}`,
  "PRAGMA foreign_keys = ON;",
  "",
];

const byFullName = new Map(snapshot.items.map((r) => [r.full_name, r]));
const guidesByName = new Map(GUIDES.map((g) => [g.fullName, g]));

// ---- repositories -------------------------------------------------------
for (const curation of CURATION) {
  const repo = byFullName.get(curation.fullName);
  if (!repo) {
    throw new Error(
      `Missing GitHub snapshot for ${curation.fullName}. Re-run scripts/fetch-github.ts so metrics stay real.`,
    );
  }
  const slug = slugFor(repo.full_name);
  const release = repo.latest_release;
  lines.push(
    `INSERT INTO repositories (slug, owner, name, full_name, html_url, homepage, description,
      summary_i18n, topics, language, license, stars, forks, open_issues, created_at, updated_at,
      pushed_at, default_branch, archived, disabled, latest_release_tag, latest_release_at,
      latest_release_url, category, chips, frameworks, difficulty, doc_score, demo_score,
      beginner_friendly, tags, featured, curation_status, data_origin, first_seen_at,
      last_synced_at, sync_status, source_verified_at)
     VALUES (${q(slug)}, ${q(repo.owner)}, ${q(repo.full_name.split("/")[1])}, ${q(repo.full_name)},
      ${q(repo.html_url)}, ${q(repo.homepage)}, ${q(repo.description)}, ${j(curation.summary)},
      ${j(repo.topics ?? [])}, ${q(repo.language)}, ${q(repo.license)}, ${q(repo.stars)},
      ${q(repo.forks)}, ${q(repo.open_issues)}, ${q(repo.created_at)}, ${q(repo.updated_at)},
      ${q(repo.pushed_at)}, ${q(repo.default_branch)}, ${q(repo.archived)}, 0,
      ${q(release?.tag ?? null)}, ${q(release?.published_at ?? null)}, ${q(release?.url ?? null)},
      ${q(curation.category)}, ${j(curation.chips)}, ${j(curation.frameworks)},
      ${q(curation.difficulty)}, ${q(curation.docScore)}, ${q(curation.demoScore)},
      ${q(curation.beginnerFriendly)}, ${j(curation.tags)}, ${q(curation.featured ?? false)},
      'published', 'github', ${q(snapshot.fetched_at)}, ${q(snapshot.fetched_at)}, 'ok',
      ${q(snapshot.fetched_at)})
     ON CONFLICT(full_name) DO UPDATE SET
      slug=excluded.slug, owner=excluded.owner, name=excluded.name, html_url=excluded.html_url,
      homepage=excluded.homepage, description=excluded.description, topics=excluded.topics,
      language=excluded.language, license=excluded.license, stars=excluded.stars,
      forks=excluded.forks, open_issues=excluded.open_issues, created_at=excluded.created_at,
      updated_at=excluded.updated_at, pushed_at=excluded.pushed_at,
      default_branch=excluded.default_branch, archived=excluded.archived,
      latest_release_tag=excluded.latest_release_tag,
      latest_release_at=excluded.latest_release_at,
      latest_release_url=excluded.latest_release_url, last_synced_at=excluded.last_synced_at,
      sync_status='ok', sync_error=NULL;`,
  );
}

// ---- baseline star snapshot (first observation) -------------------------
for (const curation of CURATION) {
  const repo = byFullName.get(curation.fullName);
  if (!repo) continue;
  lines.push(
    `INSERT OR IGNORE INTO repository_snapshots (repository_id, captured_at, stars, forks, open_issues)
     SELECT id, ${q(snapshot.fetched_at)}, ${q(repo.stars)}, ${q(repo.forks)}, ${q(repo.open_issues)}
     FROM repositories WHERE full_name = ${q(repo.full_name)};`,
  );
}

// ---- guides -------------------------------------------------------------
for (const guide of GUIDES) {
  const repo = byFullName.get(guide.fullName);
  if (!repo) continue;
  lines.push(
    `INSERT INTO project_guides (repository_id, content, confidence, editorial_updated)
     SELECT id, ${j(guide.content)}, ${q(guide.confidence)}, ${q(snapshot.fetched_at)}
     FROM repositories WHERE full_name = ${q(repo.full_name)}
     ON CONFLICT(repository_id) DO UPDATE SET content=excluded.content,
       confidence=excluded.confidence, editorial_updated=excluded.editorial_updated;`,
  );
}

// ---- tutorials ----------------------------------------------------------
for (const tutorial of TUTORIALS) {
  lines.push(
    `INSERT INTO tutorials (slug, title_i18n, url, source, author, lang, difficulty, topics,
       chips, frameworks, goal_i18n, related_repos, verified_at, check_status, data_origin)
     VALUES (${q(tutorial.slug)}, ${j(tutorial.title)}, ${q(tutorial.url)}, ${q(tutorial.source)},
       ${q(tutorial.author ?? null)}, ${q(tutorial.lang)}, ${q(tutorial.difficulty)},
       ${j(tutorial.topics)}, ${j(tutorial.chips)}, ${j(tutorial.frameworks)},
       ${j(tutorial.goal)}, ${j(tutorial.relatedRepos)}, ${q(VERIFIED_AT)}, 'ok', 'manual')
     ON CONFLICT(slug) DO UPDATE SET title_i18n=excluded.title_i18n, url=excluded.url,
       source=excluded.source, author=excluded.author, lang=excluded.lang,
       difficulty=excluded.difficulty, topics=excluded.topics, chips=excluded.chips,
       frameworks=excluded.frameworks, goal_i18n=excluded.goal_i18n,
       related_repos=excluded.related_repos, verified_at=excluded.verified_at,
       check_status='ok';`,
  );
}

// ---- chips --------------------------------------------------------------
for (const chip of CHIPS) {
  lines.push(
    `INSERT INTO chips (slug, name, family, cores, clock, sram, flash, wifi, ble, thread_zigbee,
       usb, camera, display, use_cases_i18n, boards, official_url, confidence, verified_at)
     VALUES (${q(chip.slug)}, ${q(chip.name)}, ${q(chip.family)}, ${q(chip.cores)}, ${q(chip.clock)},
       ${q(chip.sram)}, ${q(chip.flash)}, ${q(chip.wifi)}, ${q(chip.ble)},
       ${q(chip.threadZigbee)}, ${q(chip.usb)}, ${q(chip.camera)}, ${q(chip.display)},
       ${j(chip.useCases)}, ${j(chip.boards)}, ${q(chip.officialUrl)}, ${q(chip.confidence)},
       ${q(VERIFIED_AT)})
     ON CONFLICT(slug) DO UPDATE SET name=excluded.name, family=excluded.family,
       cores=excluded.cores, clock=excluded.clock, sram=excluded.sram, flash=excluded.flash,
       wifi=excluded.wifi, ble=excluded.ble, thread_zigbee=excluded.thread_zigbee,
       usb=excluded.usb, camera=excluded.camera, display=excluded.display,
       use_cases_i18n=excluded.use_cases_i18n, boards=excluded.boards,
       official_url=excluded.official_url, confidence=excluded.confidence,
       verified_at=excluded.verified_at;`,
  );
}

// ---- learning paths -----------------------------------------------------
PATHS.forEach((path, pathIndex) => {
  lines.push(
    `INSERT INTO learning_paths (slug, title_i18n, summary_i18n, level, hours, chips, frameworks,
       icon, sort_order)
     VALUES (${q(path.slug)}, ${j(path.title)}, ${j(path.summary)}, ${q(path.level)}, ${q(path.hours)},
       ${j(path.chips)}, ${j(path.frameworks)}, ${q(path.icon)}, ${q(pathIndex)})
     ON CONFLICT(slug) DO UPDATE SET title_i18n=excluded.title_i18n,
       summary_i18n=excluded.summary_i18n, level=excluded.level, hours=excluded.hours,
       chips=excluded.chips, frameworks=excluded.frameworks, icon=excluded.icon,
       sort_order=excluded.sort_order;`,
  );
  for (const step of path.steps) {
    lines.push(
      `INSERT INTO learning_path_steps (path_id, step_no, title_i18n, goal_i18n, prereq_i18n,
         resources, projects, estimate, done_when_i18n)
       SELECT id, ${q(step.no)}, ${j(step.title)}, ${j(step.goal)}, ${j(step.prereq ?? null)},
         ${j(step.resources)}, ${j(step.projects)}, ${q(step.estimate)}, ${j(step.doneWhen)}
       FROM learning_paths WHERE slug = ${q(path.slug)}
       ON CONFLICT(path_id, step_no) DO UPDATE SET title_i18n=excluded.title_i18n,
         goal_i18n=excluded.goal_i18n, prereq_i18n=excluded.prereq_i18n,
         resources=excluded.resources, projects=excluded.projects,
         estimate=excluded.estimate, done_when_i18n=excluded.done_when_i18n;`,
    );
  }
});

// ---- tags ---------------------------------------------------------------
const tagSet = new Map<string, { zh: string; en: string }>();
for (const c of CURATION) {
  for (const tag of c.tags) {
    if (!tagSet.has(tag)) tagSet.set(tag, { zh: tag, en: tag });
  }
}
for (const [slug, label] of tagSet) {
  lines.push(
    `INSERT INTO tags (slug, label_i18n, kind) VALUES (${q(slug)}, ${j(label)}, 'topic')
     ON CONFLICT(slug) DO NOTHING;`,
  );
}

writeFileSync(resolve(root, "migrations/0002_seed.sql"), `${lines.join("\n")}\n`, "utf8");

console.log(
  `seed.sql written: ${CURATION.length} repos, ${GUIDES.length} guides, ${TUTORIALS.length} tutorials, ` +
    `${CHIPS.length} chips, ${PATHS.length} paths, ${tagSet.size} tags`,
);
console.log(`repos without a guide: ${CURATION.filter((c) => !guidesByName.has(c.fullName)).map((c) => c.fullName).join(", ") || "none"}`);
